using System.Diagnostics;
using System.Runtime.Versioning;
using System.Text;
using MySqlConnector;

namespace Hoard.Setup;

/// <summary>
/// Owns the private MySQL server that ships inside the MSI: its configuration file, its data
/// directory and its Windows service. Nothing here touches a MySQL the user installed themselves —
/// the service name, the port (3307 by default), the base directory and the data directory are all
/// Hoard's own.
/// </summary>
[SupportedOSPlatform("windows")]
public static class MySqlInstance
{
    /// <summary>Writes my.ini. Rewritten on every install so an upgrade picks up new defaults.</summary>
    public static void WriteConfig(SetupContext ctx)
    {
        Directory.CreateDirectory(ctx.MySqlConfigDir);
        Directory.CreateDirectory(ctx.MySqlLogDir);

        // MySQL wants forward slashes (or escaped backslashes) in my.ini paths on Windows.
        static string P(string path) => path.Replace('\\', '/');

        var ini = $"""
            # Generated by the Hoard installer. Edit if you must, then restart the
            # "{SetupContext.MySqlServiceDisplayName}" service. A reinstall or upgrade overwrites this file.
            [mysqld]
            basedir                 = {P(ctx.MySqlBaseDir)}
            datadir                 = {P(ctx.MySqlDataDir)}
            port                    = {ctx.Port}
            # Loopback only: this server is not reachable from the network.
            bind-address            = 127.0.0.1
            log-error               = {P(ctx.MySqlErrorLog)}
            character-set-server    = utf8mb4
            collation-server        = utf8mb4_0900_ai_ci
            # A single desktop app plus the sync service; no need for the stock 151.
            max_connections         = 32
            innodb_buffer_pool_size = 256M
            innodb_flush_log_at_trx_commit = 2
            # Hoard's own schema is created by SchemaMigrator, never by the client.
            local_infile            = OFF

            [client]
            port                    = {ctx.Port}
            host                    = 127.0.0.1

            """;

        File.WriteAllText(ctx.MySqlIni, ini, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
        Log.Info($"Wrote {ctx.MySqlIni}");
    }

    public static bool IsInitialized(SetupContext ctx) =>
        Directory.Exists(Path.Combine(ctx.MySqlDataDir, "mysql"));

    /// <summary>
    /// Runs `mysqld --initialize-insecure`, which creates the system tables and a passwordless
    /// root@localhost. The password is set immediately afterwards by <see cref="Provisioner"/>,
    /// before the server ever accepts a connection from anywhere but this machine's loopback.
    /// </summary>
    public static void Initialize(SetupContext ctx)
    {
        if (IsInitialized(ctx))
        {
            Log.Info($"MySQL data directory already initialized at {ctx.MySqlDataDir}; keeping it.");
            return;
        }

        // --initialize refuses to run unless the data directory is empty or absent.
        if (Directory.Exists(ctx.MySqlDataDir) && Directory.EnumerateFileSystemEntries(ctx.MySqlDataDir).Any())
        {
            throw new InvalidOperationException(
                $"{ctx.MySqlDataDir} already contains files but is not a MySQL data directory. " +
                "Move it aside and run the installer again.");
        }
        Directory.CreateDirectory(ctx.MySqlDataDir);

        Log.Info($"Initializing the MySQL data directory at {ctx.MySqlDataDir} (this takes a few seconds)...");
        var exit = Run(ctx.MySqlDaemon, TimeSpan.FromMinutes(5),
            $"--defaults-file={ctx.MySqlIni}", "--initialize-insecure", "--console");
        if (exit != 0)
        {
            throw new InvalidOperationException(
                $"mysqld --initialize-insecure failed with exit code {exit}. See {ctx.MySqlErrorLog}.");
        }
        Log.Info("MySQL data directory initialized.");
    }

    public static void RegisterService(SetupContext ctx)
    {
        // mysqld reads the service name off the end of its own command line.
        var binPath = $"\"{ctx.MySqlDaemon}\" --defaults-file=\"{ctx.MySqlIni}\" {SetupContext.MySqlServiceName}";
        ServiceManager.CreateOrUpdate(
            SetupContext.MySqlServiceName,
            SetupContext.MySqlServiceDisplayName,
            binPath,
            "MySQL database server used exclusively by Hoard.",
            delayedAutoStart: false);
    }

    /// <summary>
    /// Waits until the server is listening, regardless of credentials. "Access denied" proves mysqld is
    /// up and answering, which is all this needs to know: the Windows service reports Running as soon as
    /// the process starts, several seconds before InnoDB recovery finishes and the port opens.
    /// </summary>
    public static async Task WaitUntilListeningAsync(SetupContext ctx, TimeSpan timeout)
    {
        var deadline = DateTime.UtcNow + timeout;
        Exception? last = null;
        while (DateTime.UtcNow < deadline)
        {
            try
            {
                await using var conn = new MySqlConnection(AdminConnectionString(ctx, "root", ""));
                await conn.OpenAsync();
                Log.Info($"MySQL is listening on port {ctx.Port}.");
                return;
            }
            // 1044/1045/1698 are all "your login was rejected", i.e. the server is up and talking.
            catch (MySqlException ex) when ((int)ex.ErrorCode is 1044 or 1045 or 1698)
            {
                Log.Info($"MySQL is listening on port {ctx.Port} (it rejected the probe login, as expected).");
                return;
            }
            catch (Exception ex)
            {
                last = ex;
                await Task.Delay(1000);
            }
        }

        throw new TimeoutException(
            $"MySQL did not start listening on 127.0.0.1:{ctx.Port} within {timeout.TotalSeconds:F0}s. " +
            $"Last error: {last?.Message}{Environment.NewLine}--- {ctx.MySqlErrorLog} ---{Environment.NewLine}" +
            ReadLogTail(ctx.MySqlErrorLog, 30));
    }

    /// <summary>Polls until the server accepts a connection, or gives up and reports the error log.</summary>
    public static async Task WaitUntilReadyAsync(SetupContext ctx, string user, string password, TimeSpan timeout)
    {
        var deadline = DateTime.UtcNow + timeout;
        Exception? last = null;
        var attempt = 0;
        while (DateTime.UtcNow < deadline)
        {
            attempt++;
            try
            {
                await using var conn = new MySqlConnection(AdminConnectionString(ctx, user, password));
                await conn.OpenAsync();
                Log.Info($"MySQL accepted a connection on port {ctx.Port} (attempt {attempt}).");
                return;
            }
            catch (Exception ex)
            {
                last = ex;
                await Task.Delay(1000);
            }
        }

        var tail = ReadLogTail(ctx.MySqlErrorLog, 30);
        throw new TimeoutException(
            $"MySQL did not become reachable on 127.0.0.1:{ctx.Port} within {timeout.TotalSeconds:F0}s. " +
            $"Last error: {last?.Message}{Environment.NewLine}--- {ctx.MySqlErrorLog} ---{Environment.NewLine}{tail}");
    }

    public static string AdminConnectionString(SetupContext ctx, string user, string password) =>
        new MySqlConnectionStringBuilder
        {
            Server = "127.0.0.1",
            Port = (uint)ctx.Port,
            UserID = user,
            Password = password,
            SslMode = MySqlSslMode.Preferred,
            ConnectionTimeout = 10,
            DefaultCommandTimeout = 120,
        }.ConnectionString;

    private static string ReadLogTail(string path, int lines)
    {
        try
        {
            if (!File.Exists(path)) return "(no error log yet)";
            var all = File.ReadAllLines(path);
            return string.Join(Environment.NewLine, all.Skip(Math.Max(0, all.Length - lines)));
        }
        catch (Exception ex)
        {
            return $"(could not read the error log: {ex.Message})";
        }
    }

    private static int Run(string exe, TimeSpan timeout, params string[] args)
    {
        var psi = new ProcessStartInfo(exe)
        {
            RedirectStandardOutput = true,
            RedirectStandardError = true,
            UseShellExecute = false,
            CreateNoWindow = true,
            WorkingDirectory = Path.GetDirectoryName(exe)!,
        };
        foreach (var a in args) psi.ArgumentList.Add(a);

        using var p = Process.Start(psi) ?? throw new InvalidOperationException($"Could not start {exe}.");
        var stdout = p.StandardOutput.ReadToEndAsync();
        var stderr = p.StandardError.ReadToEndAsync();
        if (!p.WaitForExit((int)timeout.TotalMilliseconds))
        {
            try { p.Kill(entireProcessTree: true); } catch { /* best effort */ }
            throw new TimeoutException($"{Path.GetFileName(exe)} did not finish within {timeout.TotalSeconds:F0}s.");
        }
        foreach (var line in (stdout.Result + stderr.Result).Split('\n', StringSplitOptions.RemoveEmptyEntries))
            Log.Info("  mysqld: " + line.TrimEnd('\r'));
        return p.ExitCode;
    }
}
